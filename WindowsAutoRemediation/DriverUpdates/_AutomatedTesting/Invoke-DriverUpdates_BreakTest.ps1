<#
.SYNOPSIS
    Invoke-DriverUpdates_BreakTest -- deliberately breaks the pre-flight dependency
    of Invoke-DriverUpdates.ps1, then verifies the script repairs it.

.DESCRIPTION
    Break -> verify-the-break -> remediate -> validate -> restore. Writes a uniform
    JSON result to C:\Temp\FixReport\Invoke-DriverUpdates\ for
    Invoke-FixReportAnalysis.ps1 to aggregate.

    THIS SCRIPT IS DELIBERATELY DESTRUCTIVE. It stops the Windows Update service.
    Run it only on a disposable VM or a marked test host. See Assert-DexTestHost
    in DEXTestFramework.psm1.

    VERIFY-THE-BREAK
    Every break is followed by a probe proving the component is genuinely broken.
    A break that silently no-ops would let the remediation "pass" against a healthy
    machine -- a false green, and the failure mode that makes a harness like this
    worthless. A break that cannot be verified aborts the run as BreakFailed.

    EXPECTED OUTCOMES
    Invoke-DriverUpdates.ps1 repairs exactly one thing: a stopped wuauserv in its
    Phase 1 pre-flight. Everything after that is a Windows Update query against
    Microsoft's catalogue, which a lab VM with no missing drivers answers with
    "nothing to do" (exit 0) or, in Detect mode with drivers available, exit 1.
    The script writes nothing to DEXRecords, so the single break is ExpectFixed:
      ExpectFixed        -- remediation must repair the component
      ExpectReportedOnly -- (unused) remediation must DETECT and report it only

    The remediation is invoked without Mode/DriverFilter/AllowReboot/MaxUpdates in
    the environment, so it runs in Detect mode and never downloads or installs.
    Its own WU search does reach out to Windows Update; the harness itself does not.

    WHAT IS NOT COVERED, AND WHY
      Driver discovery / download / install (Phases 2, 4, 5): a lab VM has no
        missing drivers, and injecting a missing driver means uninstalling a real
        one -- not reversible without a reboot or confined to test fixtures.
      Reboot signals (Phase 6: Auto Update\RebootRequired key and
        PendingFileRenameOperations): only evaluated in Install mode after at least
        one driver installed, so unreachable here. PendingFileRenameOperations is
        also a live system queue and not something a harness should write to.
      WU search failure (0x80240044 busy, offline): not safely injectable.
      A Disabled wuauserv: Start-Service fails and the script exits 1 without
        resetting the startup type. That is a reported failure, not a repair, and
        with no DEXRecords key there is nothing for ExpectReportedOnly to assert.
      Windows Update driver policy keys (ExcludeWUDriversInQualityUpdate and the
        like): the script does not consult them, so a break there has no defined
        expectation.

    REBOOTS
    No break in this catalog needs a reboot. The reboot plumbing (-IncludeRebootBreaks,
    -Resume) is retained for parity with the other break tests.

.PARAMETER RemediationTest
    After breaking, run Invoke-DriverUpdates.ps1 and validate the outcome.
    Without this the script breaks and reports only.

.PARAMETER Environment
    Physical (default) restores the machine when the run ends.
    Snapshot skips restore on the assumption the host reverts a checkpoint.

.PARAMETER Seed
    Replays an earlier run's random break selection exactly. Omit for a new random
    seed, which is always recorded in the result.

.PARAMETER BreakName
    Force specific breaks instead of a random selection.

.PARAMETER BreakCount
    How many components to break when selecting randomly. Default 1 (the catalog
    has a single injectable break).

.PARAMETER IncludeRebootBreaks
    Allow breaks that require a reboot to take effect. Default off.

.PARAMETER Restore
    Undo an in-flight run's breaks and exit. No remediation, no validation.

.PARAMETER Resume
    Internal. Used by the AtStartup task to re-enter after a reboot.

.PARAMETER Force
    Required acknowledgement that this machine will be broken.

.NOTES
    Script Name  : Invoke-DriverUpdates_BreakTest.ps1
    Version      : 1.0.0
    Architecture : Any (x86/x64)
    Context      : Administrator (elevated)
